"""Conservative, reversible workspace cleanup.

There is no Git history in this project, so this module never guesses that a file is
safe to delete.  Audit is read-only; quarantine requires an audited manifest hash and
uses same-volume moves; restore verifies the recorded content hash before moving back.
No code path permanently deletes a user file.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import shutil
import time
from pathlib import Path

import config


ROOT = config.ROOT.resolve()
MANIFEST_NAME = "cleanup_manifest.json"
REPORT_NAME = "cleanup_report.md"
QUARANTINE_ROOT = ROOT / "quarantine"

_PROTECTED_NAMES = {".env", "agents.md", "claude.md", ".cursorrules", "pipeline_stats.db"}
_PROTECTED_PARTS = {"assets", "out", "tests", ".claude", "quarantine"}
_DIAGNOSTIC_NAMES = {
    "_flow_bones.txt", "_gen_log.txt", "_one_run.txt", "_resume_log.txt", "_stream.txt",
    "_timing.txt", "_timing2.txt", "_verify.txt", "_study_llm", "_t_q",
    "_voice_samples", "voices_resp.json",
}
_MANUAL_REVIEW_NAMES = {"chat.py", "_gen_scripts.py", "_prompt_study.py", "scripts_data.py"}


def _relative(path: Path) -> str:
    return path.resolve().relative_to(ROOT).as_posix()


def _inside_root(path: Path) -> bool:
    try:
        path.resolve().relative_to(ROOT)
        return True
    except ValueError:
        return False


def _hash_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _hash_path(path: Path) -> str:
    if path.is_file():
        return _hash_file(path)
    digest = hashlib.sha256()
    for child in sorted(p for p in path.rglob("*") if p.is_file() and not p.is_symlink()):
        digest.update(_relative(child).encode("utf-8"))
        digest.update(_hash_file(child).encode("ascii"))
    return digest.hexdigest()


def _size(path: Path) -> int:
    if path.is_file():
        return path.stat().st_size
    return sum(p.stat().st_size for p in path.rglob("*") if p.is_file() and not p.is_symlink())


def _source_text() -> str:
    """Small reference corpus, excluding generated and protected output trees."""
    parts: list[str] = []
    for path in ROOT.rglob("*"):
        if not path.is_file() or path.suffix.lower() not in {".py", ".md", ".txt", ".json"}:
            continue
        if any(part.lower() in _PROTECTED_PARTS for part in path.parts):
            continue
        try:
            parts.append(path.read_text(encoding="utf-8", errors="ignore"))
        except OSError:
            pass
    return "\n".join(parts)


def _classification(path: Path, references: str) -> tuple[str, str, bool]:
    rel = _relative(path)
    lower_parts = {part.lower() for part in path.parts}
    if path.name.lower() in _PROTECTED_NAMES or lower_parts & _PROTECTED_PARTS:
        return "required_state", "protected project configuration, source, state, assets, tests, or run output", False
    if path.name == "__pycache__":
        return "generated_rebuildable", "Python bytecode cache; regenerated by Python", True
    if path.name in _DIAGNOSTIC_NAMES:
        used = path.name in references or rel in references
        kind = "historical_diagnostic" if used else "manual_review"
        return kind, "historical diagnostic or voice research artifact; inspect before any move", False
    if path.name in _MANUAL_REVIEW_NAMES:
        used = path.name in references or rel in references
        return "manual_review", ("referenced helper" if used else "unreferenced helper; external integration unknown"), False
    if path.suffix in {".py", ".md", ".json", ".db"}:
        return "active", "source, documentation, metadata, or database file", False
    return "manual_review", "no automatic deletion policy for this file type", False


def _canonical_manifest(payload: dict) -> str:
    body = dict(payload)
    body.pop("manifest_hash", None)
    return json.dumps(body, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def _manifest_hash(payload: dict) -> str:
    return hashlib.sha256(_canonical_manifest(payload).encode("utf-8")).hexdigest()


def audit() -> tuple[Path, Path, str]:
    references = _source_text()
    entries: list[dict] = []
    for path in sorted(ROOT.iterdir(), key=lambda p: p.name.lower()):
        if path.name in {MANIFEST_NAME, REPORT_NAME, "quarantine"}:
            continue
        if path.is_symlink():
            entries.append({
                "path": _relative(path), "classification": "manual_review",
                "reason": "symbolic link is never moved automatically", "eligible": False,
            })
            continue
        classification, reason, eligible = _classification(path, references)
        try:
            stat = path.stat()
            entries.append({
                "path": _relative(path), "kind": "directory" if path.is_dir() else "file",
                "size_bytes": _size(path), "age_days": round((time.time() - stat.st_mtime) / 86400, 2),
                "sha256": _hash_path(path), "classification": classification,
                "reference_evidence": "name/path found in project text" if path.name in references else "no direct text reference found",
                "reason": reason,
                "recommended_action": "quarantine" if eligible else "keep or manually review",
                "restore_path": _relative(path),
                "eligible": eligible,
            })
        except OSError as exc:
            entries.append({"path": _relative(path), "classification": "manual_review", "reason": str(exc), "eligible": False})

    # Finished and partial runs are protected wholesale.  Empty run folders are still
    # surfaced as review candidates, never auto-moved, so an operator can distinguish a
    # harmless cancelled start from a directory owned by an external tool.
    if config.OUT_ROOT.exists():
        for run_dir in sorted((p for p in config.OUT_ROOT.iterdir() if p.is_dir()), key=lambda p: p.name.lower()):
            try:
                if not any(run_dir.rglob("*")):
                    entries.append({
                        "path": _relative(run_dir), "kind": "directory", "size_bytes": 0,
                        "age_days": round((time.time() - run_dir.stat().st_mtime) / 86400, 2),
                        "sha256": _hash_path(run_dir), "classification": "manual_review",
                        "reference_evidence": "empty output run; output trees are protected",
                        "reason": "empty out/ run directory requires manual review; it is never auto-quarantined",
                        "recommended_action": "manual review", "restore_path": _relative(run_dir), "eligible": False,
                    })
            except OSError as exc:
                entries.append({"path": _relative(run_dir), "classification": "manual_review", "reason": str(exc), "eligible": False})

    manifest = {
        "version": 1,
        "root": str(ROOT),
        "generated_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "entries": entries,
    }
    manifest["manifest_hash"] = _manifest_hash(manifest)
    manifest_path = ROOT / MANIFEST_NAME
    manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8")

    lines = ["# Cleanup audit", "", f"Manifest hash: `{manifest['manifest_hash']}`", "", "| Path | Classification | Size | Recommended action |", "| --- | --- | ---: | --- |"]
    for entry in entries:
        lines.append(
            f"| `{entry['path']}` | {entry['classification']} | {entry.get('size_bytes', 0)} | {entry.get('recommended_action', 'manual review')} |"
        )
    lines += ["", "Only `generated_rebuildable` entries marked eligible can be quarantined by this command.", "Historical logs, voice samples, helpers, output runs, assets, databases, configuration, and integrations remain protected for manual review."]
    report_path = ROOT / REPORT_NAME
    report_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return report_path, manifest_path, manifest["manifest_hash"]


def _load_manifest(path_arg: str | None) -> tuple[Path, dict]:
    if not path_arg:
        raise SystemExit("--cleanup quarantine requires --manifest <cleanup_manifest.json>.")
    path = Path(path_arg)
    if not path.is_absolute():
        path = ROOT / path
    path = path.resolve()
    if not _inside_root(path) or not path.exists():
        raise SystemExit("Cleanup manifest must exist inside this workspace.")
    try:
        manifest = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise SystemExit(f"Cannot read cleanup manifest: {exc}")
    if Path(manifest.get("root", "")).resolve() != ROOT:
        raise SystemExit("Cleanup manifest belongs to a different workspace.")
    actual = _manifest_hash(manifest)
    if manifest.get("manifest_hash") != actual:
        raise SystemExit("Cleanup manifest hash is invalid or the manifest was edited.")
    return path, manifest


def quarantine(manifest_arg: str | None, confirm: str | None) -> Path:
    _, manifest = _load_manifest(manifest_arg)
    if not confirm or confirm != manifest["manifest_hash"]:
        raise SystemExit("Refusing quarantine: pass the exact audit manifest hash using --confirm.")
    candidates = [entry for entry in manifest.get("entries", []) if entry.get("eligible")]
    if not candidates:
        raise SystemExit("This audit contains no automatically quarantine-eligible entries.")
    batch_id = time.strftime("%Y%m%d_%H%M%S")
    batch_dir = QUARANTINE_ROOT / batch_id
    batch_dir.mkdir(parents=True, exist_ok=False)
    moved: list[dict] = []
    for entry in candidates:
        source = (ROOT / entry["path"]).resolve()
        if not _inside_root(source) or source == ROOT or not source.exists() or source.is_symlink():
            raise SystemExit(f"Unsafe or missing quarantine target: {entry['path']}")
        if source.name.lower() in _PROTECTED_NAMES or any(part.lower() in _PROTECTED_PARTS for part in source.parts):
            raise SystemExit(f"Protected target appeared in manifest: {entry['path']}")
        current_hash = _hash_path(source)
        if current_hash != entry.get("sha256"):
            raise SystemExit(f"Refusing changed target: {entry['path']} no longer matches the audit hash.")
        destination = batch_dir / entry["path"]
        destination.parent.mkdir(parents=True, exist_ok=True)
        os.replace(source, destination)
        moved.append({"original_path": entry["path"], "quarantine_path": _relative(destination), "sha256": current_hash})
    batch_manifest = {"version": 1, "batch_id": batch_id, "root": str(ROOT), "moved": moved}
    batch_manifest["batch_hash"] = _manifest_hash(batch_manifest)
    (batch_dir / "restore_manifest.json").write_text(json.dumps(batch_manifest, indent=2, ensure_ascii=False), encoding="utf-8")
    return batch_dir


def restore(batch_id: str | None) -> int:
    if not batch_id or not re.fullmatch(r"\d{8}_\d{6}", batch_id):
        raise SystemExit("--cleanup restore requires a batch id returned by quarantine.")
    batch_dir = (QUARANTINE_ROOT / batch_id).resolve()
    if not _inside_root(batch_dir) or not batch_dir.exists():
        raise SystemExit("Quarantine batch was not found in this workspace.")
    manifest_path = batch_dir / "restore_manifest.json"
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise SystemExit(f"Cannot read restore manifest: {exc}")
    if manifest.get("batch_hash") != _manifest_hash(manifest):
        raise SystemExit("Restore manifest hash is invalid.")
    for item in manifest.get("moved", []):
        source = (ROOT / item["quarantine_path"]).resolve()
        destination = (ROOT / item["original_path"]).resolve()
        if not _inside_root(source) or not _inside_root(destination) or destination.exists():
            raise SystemExit(f"Unsafe restore target or destination already exists: {item.get('original_path')}")
        if not source.exists() or _hash_path(source) != item.get("sha256"):
            raise SystemExit(f"Quarantined content changed or is missing: {item.get('original_path')}")
        destination.parent.mkdir(parents=True, exist_ok=True)
        os.replace(source, destination)
    return len(manifest.get("moved", []))


def handle_cleanup(args) -> int:
    if args.cleanup == "audit":
        report, manifest, digest = audit()
        print(f"[cleanup] audit report: {report}")
        print(f"[cleanup] manifest: {manifest}")
        print(f"[cleanup] confirmation hash: {digest}")
        return 0
    if args.cleanup == "quarantine":
        batch = quarantine(args.manifest, args.confirm)
        print(f"[cleanup] moved approved entries to {batch}")
        print(f"[cleanup] restore with: python main.py --cleanup restore --batch {batch.name}")
        return 0
    if args.cleanup == "restore":
        count = restore(args.batch)
        print(f"[cleanup] restored {count} entry/entries from batch {args.batch}")
        return 0
    raise SystemExit("Unknown cleanup operation.")
