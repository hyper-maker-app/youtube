def test_caption_no_antiquity_stamp_by_default():
    """Verify build_ass defaults historical_stamp to False and does not include antiquity stamp."""
    words = [
        {"text": "You", "start": 0.0, "end": 0.4},
        {"text": "grab", "start": 0.4, "end": 0.8},
        {"text": "the", "start": 0.8, "end": 1.0},
        {"text": "wrench", "start": 1.0, "end": 1.5},
    ]
    # Default call (modern sci-fi / horror)
    ass_text = captions.build_ass(
        words=words,
        total_duration=10.0,
        is_longform=True,
    )
    assert "ANTIQUITY" not in ass_text
    assert "HISTORICAL SITE" not in ass_text
    assert "📍" not in ass_text
    assert "Dialogue: 2," not in ass_text


def test_caption_historical_stamp_when_requested():
    """Verify historical stamp is emitted only when explicitly requested."""
    words = [
        {"text": "Cannon", "start": 0.0, "end": 0.5},
        {"text": "fire", "start": 0.5, "end": 1.0},
    ]
    ass_text = captions.build_ass(
        words=words,
        total_duration=10.0,
        is_longform=True,
        historical_stamp=True,
        topic="Gallipoli Trenches",
    )
    assert "📍" in ass_text
    assert "EraStamp" in ass_text


def test_veo_duration_snapping():
    """Verify snap_to_veo_duration strictly maps to [4.0, 6.0, 8.0, 10.0]."""
    assert snap_to_veo_duration(1.64) == 4.0
    assert snap_to_veo_duration(3.5) == 4.0
    assert snap_to_veo_duration(4.0) == 4.0
    assert snap_to_veo_duration(5.2) == 6.0
    assert snap_to_veo_duration(6.0) == 6.0
    assert snap_to_veo_duration(7.1) == 8.0
    assert snap_to_veo_duration(8.0) == 8.0
    assert snap_to_veo_duration(9.5) == 10.0
    assert snap_to_veo_duration(15.0) == 10.0


def test_universal_scenes_veo_tiers():
    """Verify all scenes generated by universal narrative engine use Veo tiers."""
    scenes = generate_universal_scenes("Rigor Mortis", "Survival Horror", duration=32, aspect="16:9")
    valid_tiers = {4.0, 6.0, 8.0, 10.0}
    for sc in scenes:
        assert sc["duration"] in valid_tiers, f"Scene {sc['id']} has invalid duration {sc['duration']}"


def test_config_ducking_parameters():
    """Verify sidechain ducking parameters are smoothed to broadcast standards."""
    assert config.DUCK_THRESHOLD == 0.04
    assert config.DUCK_RATIO == 3.5
    assert config.DUCK_ATTACK == 15
    assert config.DUCK_RELEASE == 600


def test_48khz_audio_standardization():
    """Verify AUDIO_RATE is 48000 and editor audio filter outputs 48000."""
    assert config.AUDIO_RATE == 48000
    filter_stmts = editor.build_audio_filter(vo_index=0, music_index=1)
    joined_filters = ";".join(filter_stmts)
    assert "sample_rates=48000" in joined_filters
    assert "sample_rates=44100" not in joined_filters
    assert "sidechaincompress=threshold=0.04:ratio=3.5:attack=15:release=600" in joined_filters


def test_editor_zoompan_pts_normalization():
    """Verify editor adds setpts=N/FPS/TB before zoompan to eliminate frame jitter."""
    video_stmts = editor.build_video_filter(
        n_blocks=2,
        punch_times=[],
        block_durations=[6.0, 6.0],
        target_duration=12.0,
    )
    joined = ";".join(video_stmts)
    assert f"setpts=N/{config.FPS}/TB[cat_pts]" in joined
    assert "[cat_pts]zoompan=" in joined


def test_partial_cleanup_guarantee(tmp_path: Path):
    """Simulate interrupted download and verify .partial cleanup logic."""
    target_mp4 = tmp_path / "block_01.mp4"
    partial_file = target_mp4.with_suffix(target_mp4.suffix + ".partial")
    partial_file.write_bytes(b"corrupt or partial data")

    assert partial_file.is_file()

    # Emulate native_transport try...finally cleanup
    with pytest.raises(ValueError, match="Simulated download failure"):
        try:
            # Simulate an exception during download or probing
            raise ValueError("Simulated download failure")
        finally:
            if partial_file.is_file():
                partial_file.unlink(missing_ok=True)

    assert not partial_file.is_file()
